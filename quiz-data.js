/* सभी उपलब्ध classes */
function getAvailableClasses() {
    return Object.keys(studyData);
}


/* किसी class के subjects */
function getSubjects(classNo) {
    if (!studyData[classNo]) return [];
    return Object.keys(studyData[classNo]);
}


/* किसी subject के chapters */
function getChapters(classNo, subject) {
    if (
        !studyData[classNo] ||
        !studyData[classNo][subject]
    ) {
        return [];
    }

    return Object.keys(studyData[classNo][subject]);
}


/* Chapter data */
function getChapterData(classNo, subject, chapter) {

    if (
        !studyData[classNo] ||
        !studyData[classNo][subject] ||
        !studyData[classNo][subject][chapter]
    ) {
        return null;
    }

    return studyData[classNo][subject][chapter];
}


